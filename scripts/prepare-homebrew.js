import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { parseArgs } from 'node:util';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function formula({ repository, version, filename, sha256 }) {
  if (!/^[A-Za-z0-9][A-Za-z0-9-]*\/[A-Za-z0-9][A-Za-z0-9_.-]*$/.test(repository || '')) throw new Error('Informe --repository USUARIO/REPOSITORIO do GitHub.');
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('A release Homebrew precisa de uma versão estável X.Y.Z.');
  if (!/^[a-z0-9][a-z0-9.-]*\.tgz$/.test(filename) || !/^[a-f0-9]{64}$/.test(sha256)) throw new Error('Pacote ou checksum inválido.');
  return `# Generated by npm run release:prepare. Do not edit the checksum manually.
class Webhookbox < Formula
  desc "Capture, inspect and replay webhooks from your terminal"
  homepage "https://github.com/${repository}"
  url "https://github.com/${repository}/releases/download/v${version}/${filename}"
  version "${version}"
  sha256 "${sha256}"
  license "MIT"

  depends_on "cloudflared"
  depends_on "node@24"

  def install
    # This application has no npm dependencies or build step.
    libexec.install "bin", "src", "package.json"
    (bin/"webhookbox").write <<~SH
      #!/bin/sh
      exec "#{Formula["node@24"].opt_bin}/node" "#{libexec}/bin/webhookbox.js" "$@"
    SH
    (bin/"webhookbox").chmod 0755
  end

  test do
    require "json"
    ENV["WEBHOOKBOX_DATA_DIR"] = (testpath/"data").to_s
    assert_equal version.to_s, shell_output("#{bin}/webhookbox --version").strip
    box = JSON.parse(shell_output("#{bin}/webhookbox box create homebrew-test --json"))
    assert_equal "homebrew-test", box.fetch("name")
    boxes = JSON.parse(shell_output("#{bin}/webhookbox box list --json"))
    assert_equal box.fetch("id"), boxes.first.fetch("id")
    system bin/"webhookbox", "box", "remove", "homebrew-test", "--yes"
    assert_equal [], JSON.parse(shell_output("#{bin}/webhookbox box list --json"))
  end
end
`;
}

export function prepare(args) {
  const { values } = parseArgs({ args, options: { repository: { type: 'string' }, output: { type: 'string', default: 'dist' } } });
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const filename = `${pkg.name}-${pkg.version}.tgz`;
  // Validate before writing or invoking npm.
  formula({ repository: values.repository, version: pkg.version, filename, sha256: '0'.repeat(64) });
  const out = resolve(values.output);
  mkdirSync(out, { recursive: true });
  // npm_execpath is supplied by npm run and avoids shell quoting on Windows.
  const npmArgs = ['pack', '--ignore-scripts', '--pack-destination', out];
  if (process.env.npm_execpath) execFileSync(process.execPath, [process.env.npm_execpath, ...npmArgs], { cwd: root, stdio: 'inherit' });
  else execFileSync('npm', npmArgs, { cwd: root, stdio: 'inherit' });
  const sha256 = createHash('sha256').update(readFileSync(join(out, filename))).digest('hex');
  writeFileSync(join(out, 'webhookbox.rb'), formula({ repository: values.repository, version: pkg.version, filename, sha256 }));
  writeFileSync(join(out, 'SHA256SUMS'), `${sha256}  ${filename}\n`);
  console.log(`Pacote, checksum e receita gerados em ${out}. Nada foi publicado.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { prepare(process.argv.slice(2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
